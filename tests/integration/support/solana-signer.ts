/**
 * For D02 tests only: sign unsigned transactions with a local Solana keypair (**tests only**).
 *
 * Why it lives in tests: the DFR server **never** touches private keys (ADR-007/009). Signatures for real writes must be made by
 * an external wallet; for end-to-end acceptance, D02 uses a **local test account** to play the "external signer".
 *
 * Implementation: Node's built-in `crypto` ed25519 (no new dependencies). A Solana keypair file is 64 bytes:
 * `[32-byte seed || 32-byte pubkey]`; build a PKCS8 private key from the seed to sign the message bytes.
 *
 * Only reads the path specified by env, and never prints private keys or seeds.
 */
import { readFileSync } from 'node:fs';
import { createPrivateKey, createPublicKey, sign as edSign } from 'node:crypto';

/** Fixed prefix for Solana ed25519 PKCS8 (build a private key from a raw 32-byte seed). */
const PKCS8_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex');

export interface LocalSolanaKeypair {
  /** base58 public key (used for assertions / fee payer). */
  readonly publicKeyBytes: Uint8Array;
  /** Sign the message bytes, returning a 64-byte signature. */
  sign(message: Uint8Array): Uint8Array;
}

/** Read a keypair from a JSON file generated by `solana-keygen`. The path comes from env and is not echoed to logs. */
export function loadSolanaKeypair(path: string): LocalSolanaKeypair {
  const raw = JSON.parse(readFileSync(path, 'utf8')) as number[];
  if (!Array.isArray(raw) || raw.length !== 64) {
    throw new Error('the Solana keypair file must be a 64-byte array');
  }
  const seed = Buffer.from(raw.slice(0, 32));
  const pub = Buffer.from(raw.slice(32));
  const privateKey = createPrivateKey({
    key: Buffer.concat([PKCS8_PREFIX, seed]),
    format: 'der',
    type: 'pkcs8',
  });
  const derivedPub = createPublicKey(privateKey).export({ format: 'der', type: 'spki' }).subarray(-32);
  if (!derivedPub.equals(pub)) {
    throw new Error('the keypair seed does not match the pubkey (corrupted file?)');
  }
  return {
    publicKeyBytes: Uint8Array.from(pub),
    sign: (message) => Uint8Array.from(edSign(null, Buffer.from(message), privateKey)),
  };
}
