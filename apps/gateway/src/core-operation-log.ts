/**
 * Core operation logs (the `core.operation` span layer of observability-spec §4).
 *
 * The §4 span hierarchy is:
 *
 * ```text
 * http.request (Gateway)
 *   └─ core.operation (Core domain orchestration)
 *        ├─ adapter.call
 *        │    └─ provider.request
 *        └─ store.read / store.write
 * ```
 *
 * The first four layers and store.* already have log outlets (`{provider,adapter,store}-call-log.ts`);
 * only `core.operation` lacks one — this file supplies it.
 *
 * **Honest boundary**: M1 rebuilds the hierarchy by correlating `trace_id` + `request_id`, not with genuine
 * parent/child `span_id`s. The current three layers share one request span (the spanId generated by the gateway).
 * Genuine parent/child spans (an independent spanId + parent reference per layer) need the OpenTelemetry SDK,
 * which is a later task; this section does not pretend it is already done.
 *
 * Isomorphic to the other layers: an **allowlist** mapping, so a new field on `CoreOperationRecord` forces the contract test to fail.
 */
import type { CoreOperationRecord } from '@dfr/core';

export const CORE_OPERATION_LOG_FIELDS = {
  requestId: 'request_id',
  traceId: 'trace_id',
  spanId: 'span_id',
  operation: 'operation',
  chain: 'chain',
  status: 'status',
  errorCode: 'error_code',
  category: 'error_category',
  latencyMs: 'latency_ms',
} as const satisfies Partial<Record<keyof CoreOperationRecord, string>>;

/** Fields known but deliberately not logged; currently empty (the record holds only shape and correlation fields). */
export const CORE_OPERATION_LOG_EXCLUDED: readonly (keyof CoreOperationRecord)[] = [];

export function coreOperationLogFields(record: CoreOperationRecord): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [sourceKey, logKey] of Object.entries(CORE_OPERATION_LOG_FIELDS) as [
    keyof CoreOperationRecord,
    string,
  ][]) {
    const value = record[sourceKey];
    if (value !== undefined) out[logKey] = value;
  }
  out['span'] = 'core.operation';
  out['level'] = record.status === 'success' ? 'info' : 'warn';
  out['msg'] = 'core operation';
  return out;
}

/** Log outlet; must never throw (observability failures do not affect business logic). */
export function createCoreOperationLogger(
  write: (line: string) => void,
): (record: CoreOperationRecord) => void {
  return (record) => {
    try {
      write(`${JSON.stringify(coreOperationLogFields(record))}\n`);
    } catch {
      // Observability is best-effort.
    }
  };
}
